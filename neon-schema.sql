CREATE TABLE IF NOT EXISTS officer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_no VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'officer'
        CHECK (role IN ('officer', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS property (
    property_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no VARCHAR(20) NOT NULL UNIQUE,
    address VARCHAR(255) NOT NULL,
    area VARCHAR(100) NOT NULL,
    property_type VARCHAR(30) NOT NULL
        CHECK (property_type IN ('Residential', 'Commercial', 'Agricultural', 'Industrial')),
    latitude NUMERIC(10, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_property_address ON property (address);
CREATE INDEX IF NOT EXISTS idx_property_area ON property (area);

CREATE TABLE IF NOT EXISTS tax (
    tax_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT NOT NULL REFERENCES property(property_id) ON DELETE CASCADE,
    year SMALLINT NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    status VARCHAR(10) NOT NULL DEFAULT 'UNPAID'
        CHECK (status IN ('PAID', 'UNPAID')),
    UNIQUE (property_id, year)
);

CREATE TABLE IF NOT EXISTS payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_id BIGINT NOT NULL REFERENCES tax(tax_id) ON DELETE CASCADE,
    payment_amount NUMERIC(10, 2) NOT NULL CHECK (payment_amount >= 0),
    payment_date DATE NOT NULL
);

